"""Generates Wayland client protocol bindings from a protocol XML file.

This produces the same API as `wayland-scanner client-header` and
`wayland-scanner private-code`, but the generated code only uses libwayland
functions that are available in libwayland-client 1.18 (the version in the
build sysroot). Newer versions of wayland-scanner emit calls to
wl_proxy_marshal_flags() which was only added in libwayland 1.20.

The core protocol (wayland.xml) is generated too, rather than using the
interfaces exported by libwayland-client. libwayland marshals messages using
whichever interface definitions it is given, so this allows binding core
interfaces at newer versions than the installed libwayland knows about. The
generated interfaces have hidden visibility so they don't clash with the ones
libwayland exports. Other protocols include the generated core header, which
must be in the same directory, instead of <wayland-client.h>.

Usage: wayland_scanner.py <protocol.xml> <output.h> <output.c>
"""

import os
import sys
import xml.etree.ElementTree as ET

C_TYPES = {
    'int': 'int32_t',
    'uint': 'uint32_t',
    'fixed': 'wl_fixed_t',
    'string': 'const char *',
    'array': 'struct wl_array *',
    'fd': 'int32_t',
}

SIGNATURE_CHARS = {
    'int': 'i',
    'uint': 'u',
    'fixed': 'f',
    'string': 's',
    'object': 'o',
    'new_id': 'n',
    'array': 'a',
    'fd': 'h',
}


class Arg:

  def __init__(self, element):
    self.name = element.get('name')
    self.type = element.get('type')
    self.interface = element.get('interface')
    self.allow_null = element.get('allow-null') == 'true'

  def c_type(self):
    if self.type in ('object', 'new_id'):
      return 'struct %s *' % self.interface if self.interface else 'void *'
    return C_TYPES[self.type]

  def c_declaration(self):
    c_type = self.c_type()
    separator = '' if c_type.endswith('*') else ' '
    return c_type + separator + self.name


class Message:

  def __init__(self, element, opcode):
    self.name = element.get('name')
    self.opcode = opcode
    self.since = int(element.get('since', '1'))
    self.is_destructor = element.get('type') == 'destructor'
    self.args = [Arg(a) for a in element.findall('arg')]

  def new_id_arg(self):
    for arg in self.args:
      if arg.type == 'new_id':
        return arg
    return None

  def signature(self):
    sig = str(self.since) if self.since > 1 else ''
    for arg in self.args:
      if arg.allow_null:
        sig += '?'
      if arg.type == 'new_id' and arg.interface is None:
        sig += 'su'
      sig += SIGNATURE_CHARS[arg.type]
    return sig

  def types(self):
    types = []
    for arg in self.args:
      if arg.type == 'new_id' and arg.interface is None:
        types += [None, None]
      if arg.type in ('object', 'new_id'):
        types.append(arg.interface)
      else:
        types.append(None)
    return types


class Enum:

  def __init__(self, element):
    self.name = element.get('name')
    self.entries = [(e.get('name'), e.get('value'), int(e.get('since', '1')))
                    for e in element.findall('entry')]


class Interface:

  def __init__(self, element):
    self.name = element.get('name')
    self.version = int(element.get('version'))
    self.requests = [Message(e, i) for i, e in enumerate(element.findall('request'))]
    self.events = [Message(e, i) for i, e in enumerate(element.findall('event'))]
    self.enums = [Enum(e) for e in element.findall('enum')]


def referenced_interfaces(interfaces):
  names = set()
  for interface in interfaces:
    names.add(interface.name)
    for message in interface.requests + interface.events:
      for arg in message.args:
        if arg.interface:
          names.add(arg.interface)
  return sorted(names)


def generate_header(protocol_name, interfaces):
  guard = '%s_CLIENT_PROTOCOL_H_' % protocol_name.upper().replace('-', '_')
  out = []
  out.append('/* Generated by wayland_scanner.py. Do not edit. */\n')
  out.append('#ifndef %s\n#define %s\n' % (guard, guard))
  if protocol_name == 'wayland':
    core_include = '#include <wayland-client-core.h>'
  else:
    core_include = '#include "wayland-client-protocol.h"'
  out.append('#include <stddef.h>\n#include <stdint.h>\n\n%s\n' % core_include)
  out.append('#ifdef __cplusplus\nextern "C" {\n#endif\n')

  for name in referenced_interfaces(interfaces):
    out.append('struct %s;' % name)
  out.append('')
  for interface in interfaces:
    out.append('extern const struct wl_interface %s_interface;' % interface.name)
  out.append('')

  for interface in interfaces:
    out.append(generate_interface_header(interface))

  out.append('#ifdef __cplusplus\n}  // extern "C"\n#endif\n')
  out.append('#endif  // %s' % guard)
  return '\n'.join(out) + '\n'


def generate_interface_header(interface):
  name = interface.name
  upper = name.upper()
  out = []

  for enum in interface.enums:
    enum_name = '%s_%s' % (name, enum.name)
    guard = '%s_ENUM' % enum_name.upper()
    out.append('#ifndef %s\n#define %s' % (guard, guard))
    out.append('enum %s {' % enum_name)
    for entry_name, value, _ in enum.entries:
      out.append('  %s_%s = %s,' % (enum_name.upper(), entry_name.upper(), value))
    out.append('};')
    for entry_name, _, since in enum.entries:
      if since > 1:
        out.append(
            '#define %s_%s_SINCE_VERSION %d' % (enum_name.upper(), entry_name.upper(), since)
        )
    out.append('#endif  // %s\n' % guard)

  if interface.events:
    out.append('struct %s_listener {' % name)
    for event in interface.events:
      params = ['void *data', 'struct %s *%s' % (name, name)]
      params += [arg.c_declaration() for arg in event.args]
      out.append('  void (*%s)(%s);' % (event.name, ', '.join(params)))
    out.append('};\n')
    out.append(
        'static inline int %s_add_listener(struct %s *%s, '
        'const struct %s_listener *listener, void *data) {' % (name, name, name, name)
    )
    out.append(
        '  return wl_proxy_add_listener((struct wl_proxy *)%s, '
        '(void (**)(void))listener, data);' % name
    )
    out.append('}\n')

  for request in interface.requests:
    out.append('#define %s_%s %d' % (upper, request.name.upper(), request.opcode))
  for event in interface.events:
    out.append('#define %s_%s_SINCE_VERSION %d' % (upper, event.name.upper(), event.since))
  for request in interface.requests:
    out.append('#define %s_%s_SINCE_VERSION %d' % (upper, request.name.upper(), request.since))
  out.append('')

  out.append(
      'static inline void %s_set_user_data(struct %s *%s, void *user_data) {' % (name, name, name)
  )
  out.append('  wl_proxy_set_user_data((struct wl_proxy *)%s, user_data);\n}\n' % name)
  out.append('static inline void *%s_get_user_data(struct %s *%s) {' % (name, name, name))
  out.append('  return wl_proxy_get_user_data((struct wl_proxy *)%s);\n}\n' % name)
  out.append('static inline uint32_t %s_get_version(struct %s *%s) {' % (name, name, name))
  out.append('  return wl_proxy_get_version((struct wl_proxy *)%s);\n}\n' % name)

  has_destroy = any(r.name == 'destroy' for r in interface.requests)
  if not has_destroy and name != 'wl_display':
    out.append('static inline void %s_destroy(struct %s *%s) {' % (name, name, name))
    out.append('  wl_proxy_destroy((struct wl_proxy *)%s);\n}\n' % name)

  for request in interface.requests:
    out.append(generate_request(interface, request))

  return '\n'.join(out)


def generate_request(interface, request):
  name = interface.name
  opcode = '%s_%s' % (name.upper(), request.name.upper())
  new_id = request.new_id_arg()

  params = ['struct %s *%s' % (name, name)]
  for arg in request.args:
    if arg.type == 'new_id':
      if arg.interface is None:
        params += ['const struct wl_interface *interface', 'uint32_t version']
      continue
    params.append(arg.c_declaration())

  if new_id is None:
    return_type = 'void '
  elif new_id.interface is None:
    return_type = 'void *'
  else:
    return_type = 'struct %s *' % new_id.interface

  call_args = []
  for arg in request.args:
    if arg.type == 'new_id':
      if arg.interface is None:
        call_args += ['interface->name', 'version']
      call_args.append('NULL')
    else:
      call_args.append(arg.name)
  proxy = '(struct wl_proxy *)%s' % name

  out = []
  out.append('static inline %s%s_%s(%s) {' % (return_type, name, request.name, ', '.join(params)))
  if new_id is None:
    out.append('  wl_proxy_marshal(%s);' % ', '.join([proxy, opcode] + call_args))
  elif new_id.interface is None:
    out.append(
        '  struct wl_proxy *id = wl_proxy_marshal_constructor_versioned(%s);' %
        ', '.join([proxy, opcode, 'interface', 'version'] + call_args)
    )
  else:
    out.append(
        '  struct wl_proxy *id = wl_proxy_marshal_constructor(%s);' %
        ', '.join([proxy, opcode, '&%s_interface' % new_id.interface] + call_args)
    )

  if request.is_destructor:
    out.append('  wl_proxy_destroy(%s);' % proxy)

  if new_id is not None:
    if new_id.interface is None:
      out.append('  return (void *)id;')
    else:
      out.append('  return (struct %s *)id;' % new_id.interface)
  out.append('}\n')
  return '\n'.join(out)


def generate_code(protocol_name, interfaces):
  types_name = '%s_types' % protocol_name.replace('-', '_')
  out = []
  out.append('/* Generated by wayland_scanner.py. Do not edit. */\n')
  out.append('#include <stdint.h>\n#include <stdlib.h>\n\n#include "wayland-util.h"\n')

  for name in referenced_interfaces(interfaces):
    out.append('extern const struct wl_interface %s_interface;' % name)
  out.append('')

  types = []
  offsets = {}
  for interface in interfaces:
    for kind, messages in (('requests', interface.requests), ('events', interface.events)):
      for message in messages:
        offsets[(interface.name, kind, message.name)] = len(types)
        types += message.types()

  out.append('static const struct wl_interface *%s[] = {' % types_name)
  if not types:
    out.append('  NULL,')
  for t in types:
    out.append('  %s,' % ('&%s_interface' % t if t else 'NULL'))
  out.append('};\n')

  for interface in interfaces:
    for kind, messages in (('requests', interface.requests), ('events', interface.events)):
      if not messages:
        continue
      out.append('static const struct wl_message %s_%s[] = {' % (interface.name, kind))
      for message in messages:
        offset = offsets[(interface.name, kind, message.name)]
        out.append(
            '  {"%s", "%s", %s + %d},' % (message.name, message.signature(), types_name, offset)
        )
      out.append('};\n')

    out.append(
        '__attribute__((visibility("hidden"))) const struct wl_interface %s_interface = {' %
        interface.name
    )
    out.append('  "%s", %d,' % (interface.name, interface.version))
    for kind, messages in (('requests', interface.requests), ('events', interface.events)):
      if messages:
        out.append('  %d, %s_%s,' % (len(messages), interface.name, kind))
      else:
        out.append('  0, NULL,')
    out.append('};\n')

  return '\n'.join(out)


def main():
  if len(sys.argv) != 4:
    sys.stderr.write(__doc__)
    return 1
  input_path, header_path, code_path = sys.argv[1:]
  root = ET.parse(input_path).getroot()
  protocol_name = os.path.splitext(os.path.basename(input_path))[0]
  interfaces = [Interface(e) for e in root.findall('interface')]

  with open(header_path, 'w') as f:
    f.write(generate_header(protocol_name, interfaces))
  with open(code_path, 'w') as f:
    f.write(generate_code(protocol_name, interfaces))
  return 0


if __name__ == '__main__':
  sys.exit(main())
